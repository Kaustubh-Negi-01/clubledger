IF (
      OLD.event_id IS DISTINCT FROM NEW.event_id OR
      OLD.body_sha256 IS DISTINCT FROM NEW.body_sha256 OR
      OLD.raw_body IS DISTINCT FROM NEW.raw_body OR
      OLD.type IS DISTINCT FROM NEW.type OR

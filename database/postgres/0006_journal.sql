IF (SELECT status FROM terms WHERE id = NEW.adjusts_term_id) <> 'CLOSED' THEN RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'adjusts_term_id must reference a CLOSED term'; END IF;
END IF;

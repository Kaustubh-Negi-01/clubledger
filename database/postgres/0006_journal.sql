CREATE FUNCTION trg_line_insert_draft_only_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
IF (SELECT status FROM journal_entries WHERE id = NEW.entry_id) IS NULL THEN RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'Parent journal entry does not exist'; END IF;
IF (SELECT status FROM journal_entries WHERE id = NEW.entry_id) <> 'DRAFT' THEN RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'Lines can only be inserted into DRAFT entries'; END IF;
RETURN NEW;
END;
$$;
CREATE TRIGGER trg_line_insert_draft_only BEFORE INSERT ON journal_lines FOR EACH ROW EXECUTE FUNCTION trg_line_insert_draft_only_fn();

CREATE FUNCTION trg_line_update_blocked_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
IF NEW.entry_id <> OLD.entry_id THEN RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'entry_id cannot be changed'; END IF;
IF (SELECT status FROM journal_entries WHERE id = OLD.entry_id) = 'POSTED' THEN RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'Cannot update lines of a POSTED entry'; END IF;
IF (SELECT status FROM journal_entries WHERE id = NEW.entry_id) = 'POSTED' THEN RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'Cannot move lines into a POSTED entry'; END IF;
RETURN NEW;
END;
$$;
CREATE TRIGGER trg_line_update_blocked BEFORE UPDATE ON journal_lines FOR EACH ROW EXECUTE FUNCTION trg_line_update_blocked_fn();

CREATE FUNCTION trg_line_delete_draft_only_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
IF (SELECT status FROM journal_entries WHERE id = OLD.entry_id) = 'POSTED' THEN RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'Cannot delete lines from a POSTED entry'; END IF;
RETURN OLD;
END;
$$;
CREATE TRIGGER trg_line_delete_draft_only BEFORE DELETE ON journal_lines FOR EACH ROW EXECUTE FUNCTION trg_line_delete_draft_only_fn();


CREATE TABLE accounts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  type TEXT NOT NULL CHECK (type IN ('ASSET','LIABILITY','INCOME','EXPENSE')),
  created_at TEXT NOT NULL
);

CREATE TABLE journal_entries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  term_id BIGINT NOT NULL REFERENCES terms(id),
  entry_date TEXT NOT NULL,
  source_type TEXT NOT NULL CHECK (source_type IN ('payment','payment_event','expense','adjustment')),
  source_id BIGINT NOT NULL,
  source_event TEXT NOT NULL,
  memo TEXT,
  status TEXT NOT NULL CHECK (status IN ('DRAFT','POSTED')),
  posted_at TEXT,
  reverses_entry_id BIGINT REFERENCES journal_entries(id),
  adjusts_term_id BIGINT REFERENCES terms(id),
  created_at TEXT NOT NULL,
  UNIQUE (source_type, source_id, source_event),
  CHECK ((status = 'POSTED') = (posted_at IS NOT NULL)),
  CHECK (adjusts_term_id IS NULL OR adjusts_term_id <> term_id),
  CHECK (adjusts_term_id IS NULL OR source_type = 'adjustment'),
  CHECK (source_event NOT LIKE '%_reversal' OR reverses_entry_id IS NOT NULL)
);

CREATE INDEX ix_entries_term ON journal_entries(term_id, entry_date);

CREATE INDEX ix_entries_asof ON journal_entries(status, entry_date);

CREATE INDEX ix_entries_source ON journal_entries(source_type, source_id);

CREATE UNIQUE INDEX ux_entries_reversal ON journal_entries(reverses_entry_id) WHERE reverses_entry_id IS NOT NULL;

CREATE TABLE journal_lines (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entry_id BIGINT NOT NULL REFERENCES journal_entries(id),
  account_id BIGINT NOT NULL REFERENCES accounts(id),
  debit_paise BIGINT NOT NULL DEFAULT 0 CHECK (debit_paise >= 0),
  credit_paise BIGINT NOT NULL DEFAULT 0 CHECK (credit_paise >= 0),
  created_at TEXT NOT NULL,
  CHECK ((debit_paise = 0) <> (credit_paise = 0))
);

CREATE INDEX ix_lines_entry ON journal_lines(entry_id);

CREATE INDEX ix_lines_account ON journal_lines(account_id);

CREATE FUNCTION trg_entry_insert_draft_only_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
IF NEW.status <> 'DRAFT' THEN RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'Direct INSERT of POSTED entry is not allowed'; END IF;
IF (SELECT status FROM terms WHERE id = NEW.term_id) <> 'OPEN' THEN RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'TERM_CLOSED'; END IF;
IF NEW.adjusts_term_id IS NOT NULL AND (SELECT status FROM terms WHERE id = NEW.adjusts_term_id) <> 'CLOSED' THEN RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'adjusts_term_id must reference a CLOSED term'; END IF;
RETURN NEW;
END;
$$;
CREATE TRIGGER trg_entry_insert_draft_only BEFORE INSERT ON journal_entries FOR EACH ROW EXECUTE FUNCTION trg_entry_insert_draft_only_fn();

CREATE FUNCTION trg_entry_adjusts_term_check_fn() RETURNS trigger LANGUAGE plpgsql AS $$

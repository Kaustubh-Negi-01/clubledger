$$;
CREATE TRIGGER trg_entry_adjusts_term_check BEFORE UPDATE OF adjusts_term_id ON journal_entries FOR EACH ROW EXECUTE FUNCTION trg_entry_adjusts_term_check_fn();

CREATE FUNCTION trg_entry_post_check_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
IF NEW.status = 'POSTED' THEN
IF OLD.status <> 'DRAFT' THEN RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'Only DRAFT entries can be transitioned to POSTED'; END IF;
IF (SELECT status FROM terms WHERE id = NEW.term_id) <> 'OPEN' THEN RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'TERM_CLOSED'; END IF;
IF NEW.adjusts_term_id IS NOT NULL AND (SELECT status FROM terms WHERE id = NEW.adjusts_term_id) <> 'CLOSED' THEN RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'adjusts_term_id must reference a CLOSED term'; END IF;
IF (SELECT COUNT(*) FROM journal_lines WHERE entry_id = NEW.id) < 2 THEN RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'Posted entry must have at least 2 lines'; END IF;
IF (SELECT COALESCE(SUM(debit_paise), 0) FROM journal_lines WHERE entry_id = NEW.id) <>
         (SELECT COALESCE(SUM(credit_paise), 0) FROM journal_lines WHERE entry_id = NEW.id) THEN RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'Debits and credits must balance'; END IF;
IF (SELECT COALESCE(SUM(debit_paise), 0) FROM journal_lines WHERE entry_id = NEW.id) <= 0 THEN RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'Total amount must be greater than zero'; END IF;
END IF;
RETURN NEW;
END;
$$;
CREATE TRIGGER trg_entry_post_check BEFORE UPDATE OF status ON journal_entries FOR EACH ROW EXECUTE FUNCTION trg_entry_post_check_fn();


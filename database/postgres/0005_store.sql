CREATE TABLE products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, description TEXT NOT NULL DEFAULT '',
  base_price_paise BIGINT NOT NULL CHECK (base_price_paise > 0),
  is_active BIGINT NOT NULL DEFAULT 1 CHECK (is_active IN (0,1)), created_at TEXT NOT NULL
);

CREATE TABLE variants (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT NOT NULL REFERENCES products(id),
  sku TEXT NOT NULL UNIQUE, size TEXT NOT NULL,
  physical_qty BIGINT NOT NULL CHECK (physical_qty >= 0),   
  reserved_qty BIGINT NOT NULL DEFAULT 0 CHECK (reserved_qty >= 0),   
  created_at TEXT NOT NULL,
  UNIQUE (product_id, size),
  CHECK (reserved_qty <= physical_qty)
);

CREATE TABLE merch_orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id),
  status TEXT NOT NULL CHECK (status IN ('RESERVED','PAID','PICKED_UP','CANCELLED','EXPIRED','REFUNDED')),
  expires_at TEXT NOT NULL, total_paise BIGINT NOT NULL CHECK (total_paise >= 0),
  price_tier TEXT NOT NULL CHECK (price_tier IN ('MEMBER','PUBLIC')),
  payment_id BIGINT REFERENCES payments(id),
  picked_up_at TEXT, picked_up_by BIGINT REFERENCES users(id),
  created_at TEXT NOT NULL
);

CREATE INDEX ix_orders_user ON merch_orders(user_id);

CREATE INDEX ix_orders_expiry ON merch_orders(status, expires_at);

CREATE TABLE merch_order_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES merch_orders(id),
  variant_id BIGINT NOT NULL REFERENCES variants(id),
  qty BIGINT NOT NULL CHECK (qty BETWEEN 1 AND 10),
  unit_price_paise BIGINT NOT NULL CHECK (unit_price_paise > 0),
  created_at TEXT NOT NULL,
  UNIQUE (order_id, variant_id)
);

ALTER TABLE products ENABLE ROW LEVEL SECURITY;

ALTER TABLE variants ENABLE ROW LEVEL SECURITY;

ALTER TABLE merch_orders ENABLE ROW LEVEL SECURITY;

ALTER TABLE merch_order_items ENABLE ROW LEVEL SECURITY;

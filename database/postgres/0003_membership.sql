CREATE TABLE membership_plans (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code TEXT NOT NULL UNIQUE, name TEXT NOT NULL,
  dues_paise BIGINT NOT NULL CHECK (dues_paise > 0),
  ticket_discount_bps BIGINT NOT NULL CHECK (ticket_discount_bps BETWEEN 0 AND 10000),
  merch_discount_bps  BIGINT NOT NULL CHECK (merch_discount_bps  BETWEEN 0 AND 10000),
  is_active BIGINT NOT NULL DEFAULT 1 CHECK (is_active IN (0,1)),
  created_at TEXT NOT NULL
);

CREATE TABLE memberships (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id),
  plan_id BIGINT NOT NULL REFERENCES membership_plans(id),
  membership_year TEXT NOT NULL,                    
  status TEXT NOT NULL CHECK (status IN ('PENDING','ACTIVE','EXPIRED','REVOKED','CANCELLED')),
  starts_at TEXT NOT NULL,                          
  expires_at TEXT NOT NULL,                         
  member_code TEXT UNIQUE,                          
  qr_token TEXT UNIQUE,                             
  payment_id BIGINT REFERENCES payments(id),
  verified_by BIGINT REFERENCES users(id), verified_at TEXT,
  created_at TEXT NOT NULL,
  CHECK (expires_at > starts_at),
  CHECK (status <> 'ACTIVE' OR (member_code IS NOT NULL AND qr_token IS NOT NULL))
);

CREATE UNIQUE INDEX ux_member_user_year ON memberships(user_id, membership_year) WHERE status IN ('PENDING','ACTIVE');

CREATE INDEX ix_memberships_expiry ON memberships(status, expires_at);

ALTER TABLE membership_plans ENABLE ROW LEVEL SECURITY;

ALTER TABLE memberships ENABLE ROW LEVEL SECURITY;

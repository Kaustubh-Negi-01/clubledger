CREATE TABLE announcements (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, author_id BIGINT NOT NULL REFERENCES users(id), term_id BIGINT NOT NULL REFERENCES terms(id),
 title TEXT NOT NULL, body TEXT NOT NULL, status TEXT NOT NULL CHECK(status IN ('DRAFT','PUBLISHED')),
 published_at TEXT, created_at TEXT NOT NULL, CHECK((status='PUBLISHED')=(published_at IS NOT NULL))
);

CREATE FUNCTION immutable_announcements_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
IF OLD.status='PUBLISHED' THEN
RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'PUBLISHED_IMMUTABLE'; 
END IF;
RETURN NEW;
END;
$$;
CREATE TRIGGER immutable_announcements BEFORE UPDATE ON announcements FOR EACH ROW EXECUTE FUNCTION immutable_announcements_fn();

CREATE FUNCTION preserve_announcements_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
IF OLD.status='PUBLISHED' THEN
RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'PUBLISHED_IMMUTABLE'; 
END IF;
RETURN OLD;
END;
$$;
CREATE TRIGGER preserve_announcements BEFORE DELETE ON announcements FOR EACH ROW EXECUTE FUNCTION preserve_announcements_fn();

CREATE TABLE subscribers (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email TEXT NOT NULL UNIQUE, user_id BIGINT REFERENCES users(id),
 status TEXT NOT NULL CHECK(status IN ('SUBSCRIBED','UNSUBSCRIBED')), unsub_token TEXT NOT NULL UNIQUE,
 subscribed_at TEXT NOT NULL, unsubscribed_at TEXT, created_at TEXT NOT NULL
);

CREATE TABLE mail_outbox (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, dedupe_key TEXT NOT NULL UNIQUE, to_email TEXT NOT NULL, subject TEXT NOT NULL, body TEXT NOT NULL,
 kind TEXT NOT NULL CHECK(kind IN ('ANNOUNCEMENT','RENEW_30D','RENEW_7D','EXPIRED')),
 ref_table TEXT NOT NULL CHECK(ref_table IN ('announcements','memberships')), ref_id BIGINT NOT NULL,
 status TEXT NOT NULL CHECK(status IN ('QUEUED','SENT','FAILED','SUPPRESSED')), suppressed_reason TEXT,
 attempts BIGINT NOT NULL DEFAULT 0, last_error TEXT, processed_at TEXT, created_at TEXT NOT NULL,
 CHECK((status='SUPPRESSED')=(suppressed_reason IS NOT NULL))
);

CREATE INDEX ix_outbox_status ON mail_outbox(status);

CREATE TABLE mail_capture (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, outbox_id BIGINT NOT NULL UNIQUE REFERENCES mail_outbox(id), to_email TEXT NOT NULL,
 subject TEXT NOT NULL, body TEXT NOT NULL, captured_at TEXT NOT NULL, created_at TEXT NOT NULL
);

CREATE UNIQUE INDEX subscribers_email_casefold ON subscribers(lower(email));


-- Private persistent bytes: receipt metadata and content commit in one transaction.
CREATE TABLE receipt_content (
 stored_name TEXT PRIMARY KEY REFERENCES receipts(stored_name),
 content BYTEA NOT NULL CHECK(octet_length(content) BETWEEN 1 AND 3145728)
);
ALTER TABLE receipt_content ENABLE ROW LEVEL SECURITY;
-- Shared rate limits survive cold starts and apply across serverless instances.
CREATE TABLE rate_limit_attempts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 bucket TEXT NOT NULL, attempted_at DOUBLE PRECISION NOT NULL
);
CREATE INDEX ix_rate_attempts ON rate_limit_attempts(bucket, attempted_at);
ALTER TABLE rate_limit_attempts ENABLE ROW LEVEL SECURITY;

CREATE TABLE fundraisers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  term_id BIGINT NOT NULL REFERENCES terms(id),
  title TEXT NOT NULL,
  goal_paise BIGINT CHECK (goal_paise IS NULL OR goal_paise > 0),
  status TEXT NOT NULL CHECK (status IN ('PLANNING','ACTIVE','DONE','CANCELLED')),
  created_at TEXT NOT NULL
);

CREATE TABLE tasks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fundraiser_id BIGINT NOT NULL REFERENCES fundraisers(id),
  title TEXT NOT NULL,
  owner_user_id BIGINT REFERENCES users(id),
  due_at TEXT,
  status TEXT NOT NULL CHECK (status IN ('TODO','DOING','DONE','BLOCKED')),
  created_at TEXT NOT NULL,
  UNIQUE (id, fundraiser_id)
);

ALTER TABLE fundraisers ENABLE ROW LEVEL SECURITY;

ALTER TABLE tasks ENABLE ROW LEVEL SECURITY;

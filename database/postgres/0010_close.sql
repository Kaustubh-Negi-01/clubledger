-- PostgreSQL counterpart of 0010_close.sql. Keep SQLite migrations unchanged.

CREATE TABLE close_snapshots (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, term_id BIGINT NOT NULL UNIQUE REFERENCES terms(id), taken_at TEXT NOT NULL,
 taken_by BIGINT NOT NULL REFERENCES users(id), watermark_entry_id BIGINT NOT NULL,
 totals_json TEXT NOT NULL, content_sha256 TEXT NOT NULL, created_at TEXT NOT NULL
);

CREATE FUNCTION immutable_snapshot_update_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'SNAPSHOT_IMMUTABLE'; 
RETURN NEW;
END;
$$;
CREATE TRIGGER immutable_snapshot_update BEFORE UPDATE ON close_snapshots FOR EACH ROW EXECUTE FUNCTION immutable_snapshot_update_fn();

CREATE FUNCTION immutable_snapshot_delete_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'SNAPSHOT_IMMUTABLE'; 
RETURN OLD;
END;
$$;
CREATE TRIGGER immutable_snapshot_delete BEFORE DELETE ON close_snapshots FOR EACH ROW EXECUTE FUNCTION immutable_snapshot_delete_fn();

CREATE TABLE close_checks (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, term_id BIGINT NOT NULL REFERENCES terms(id), code TEXT NOT NULL,
 passed BIGINT NOT NULL CHECK(passed IN (0,1)), detail TEXT, evaluated_at TEXT NOT NULL, created_at TEXT NOT NULL
);

CREATE TABLE officer_handover (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, term_id BIGINT NOT NULL UNIQUE REFERENCES terms(id),
 from_user_id BIGINT NOT NULL REFERENCES users(id), to_user_id BIGINT NOT NULL REFERENCES users(id),
 notes TEXT, role_changes_json TEXT NOT NULL, completed_at TEXT NOT NULL, created_at TEXT NOT NULL
);

ALTER TABLE close_snapshots ENABLE ROW LEVEL SECURITY;

ALTER TABLE close_checks ENABLE ROW LEVEL SECURITY;

ALTER TABLE officer_handover ENABLE ROW LEVEL SECURITY;
